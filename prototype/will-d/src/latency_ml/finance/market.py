"""Synthetic event-driven market generator for the Phase 3 mechanism test.

**The generator contains no latency variable, and must never gain one.** It
produces a market process and nothing else. The decision-to-execution delay is
applied afterwards, by :mod:`latency_ml.finance.replay`, to a stream that has
already been generated. That separation is what makes the latency sweep a genuine
intervention on timing rather than a change to the market being observed.

Mechanism the generator encodes
-------------------------------
A hidden short-lived state ``s_t in {-1, 0, +1}`` is switched on by an exogenous
trigger, persists for a stochastic number of events, and decays back to neutral.
While it is active it tilts both order flow and the price increment. Nothing
else in the process knows the state exists: an observer sees only the resulting
book, sizes and flow.

The causal chain the project needs is:

    latent persistence -> future order flow -> decaying opportunity
                       -> delayed execution -> economic loss

and each arrow is separately testable:

* the persistence ablation switches decay off, so the first two arrows break;
* the decoupled control switches off the state-to-flow link, so the middle arrow
  breaks;
* both should remove the latency curve, and if either fails to, the curve was
  baked into the replay rather than generated by the market.
"""

from __future__ import annotations

from dataclasses import dataclass, replace
from typing import Literal

import numpy as np
from numpy.typing import NDArray

#: Latent state values. 0 is neutral.
NEUTRAL: int = 0


@dataclass(frozen=True)
class GeneratorParams:
    """Parameters of the synthetic market.

    Attributes:
        n_events: Length of the generated stream.
        seed: RNG seed. Fixes the entire stream, so latency conditions can be
            paired at the event-stream level.
        trigger_prob: Per-event probability of an exogenous opportunity.
        mean_persistence_events: Mean number of events the latent state stays
            active once triggered. Large values approach the persistent ablation.
        drift_per_event: Signed mean price increment while the state is active,
            in price units per event.
        noise_per_event: Standard deviation of the symmetric price increment.
        flow_sensitivity: How far order flow tilts toward the state's direction.
            0.25 means 75% buy-side flow while the state is positive.
        base_spread: Half-spread in price units.
        base_size: Base resting size per side.
        decoupled: Falsification control. Removes the state-to-flow and
            state-to-price links while leaving triggers, persistence and noise
            in place, so any remaining latency curve must come from the replay.
        persistence_mode: ``"geometric"`` for the main process, ``"persistent"``
            for the ablation.
        event_spacing_ns: Wall-clock gap between consecutive events. This is the
            only parameter that sets the *physical* scale of the process; every
            other generator parameter is expressed in events, so changing the
            spacing rescales physical time while leaving the dimensionless
            relationships between delay, persistence and markout untouched.
            It also fixes the resolution floor: a delay can never resolve finer
            than one event spacing.
        persistent_lifetime_events: Lifetime used in ``persistent`` mode. It is
            long and finite rather than infinite on purpose: an unbounded drift
            runs the price away over the stream, and since transaction cost
            scales with the price level the runaway then cancels the opportunity
            it was supposed to preserve. Long-and-finite keeps the signal alive
            across the whole delay sweep without that artefact.
    """

    n_events: int = 200_000
    seed: int = 7
    trigger_prob: float = 0.02
    mean_persistence_events: float = 25.0
    drift_per_event: float = 0.02
    noise_per_event: float = 0.05
    flow_sensitivity: float = 0.25
    base_spread: float = 0.01
    base_size: float = 100.0
    event_spacing_ns: int = 1_000_000
    decoupled: bool = False
    persistence_mode: Literal["geometric", "persistent"] = "geometric"
    persistent_lifetime_events: int = 20_000

    def __post_init__(self) -> None:
        if self.n_events < 2:
            raise ValueError("n_events must be at least 2")
        if self.event_spacing_ns <= 0:
            raise ValueError("event_spacing_ns must be positive")
        if not 0.0 <= self.trigger_prob <= 1.0:
            raise ValueError("trigger_prob must be in [0, 1]")
        if self.mean_persistence_events <= 0:
            raise ValueError("mean_persistence_events must be positive")
        if not 0.0 <= self.flow_sensitivity <= 0.5:
            raise ValueError("flow_sensitivity must be in [0, 0.5]")
        if self.persistence_mode not in ("geometric", "persistent"):
            raise ValueError(f"unknown persistence_mode {self.persistence_mode!r}")

    @property
    def effective_lifetime_events(self) -> float:
        """Mean number of events the state stays active once triggered."""
        if self.persistence_mode == "persistent":
            return float(self.persistent_lifetime_events)
        return self.mean_persistence_events

    @property
    def decay_prob(self) -> float:
        """Per-event probability the latent state returns to neutral."""
        return min(1.0 / self.effective_lifetime_events, 1.0)


@dataclass(frozen=True)
class MarketStream:
    """A generated market, as arrays indexed by event.

    ``signal`` is hidden ground truth. It exists for evaluation and for the
    oracle in the mechanism test, and must never be exposed as an agent feature.
    Everything else is observable at the corresponding event.

    Attributes:
        times_ns: Event timestamps in nanoseconds.
        mid: Mid price at each event.
        signal: Hidden latent state in {-1, 0, +1}.
        buy_fraction: Fraction of order flow that is buy-side, in [0, 1].
        spread: Full spread in price units.
        bid_size: Resting size at the best bid.
        ask_size: Resting size at the best ask.
    """

    times_ns: NDArray[np.int64]
    mid: NDArray[np.float64]
    signal: NDArray[np.int8]
    buy_fraction: NDArray[np.float64]
    spread: NDArray[np.float64]
    bid_size: NDArray[np.float64]
    ask_size: NDArray[np.float64]

    def __len__(self) -> int:
        return int(self.mid.shape[0])

    @property
    def imbalance(self) -> NDArray[np.float64]:
        """Order-flow imbalance in [-1, 1]; positive is buy pressure."""
        return 2.0 * self.buy_fraction - 1.0


def _latent_path(params: GeneratorParams, rng: np.random.Generator) -> NDArray[np.int8]:
    """Hidden state trajectory.

    Triggers are exogenous and independent of the state, so an observer cannot
    distinguish "no opportunity here" from "opportunity not yet fired" except by
    waiting.
    """
    signal = np.zeros(params.n_events, dtype=np.int8)
    state = NEUTRAL
    remaining = 0
    for t in range(params.n_events):
        if remaining == 0:
            if rng.random() < params.trigger_prob:
                state = 1 if rng.random() < 0.5 else -1
                # Geometric lifetime, or effectively unbounded under ablation.
                remaining = 1 + int(rng.geometric(max(params.decay_prob, 1e-12)))
            else:
                state = NEUTRAL
        signal[t] = state
        if remaining > 0:
            remaining -= 1
            if remaining == 0:
                state = NEUTRAL
    return signal


def generate(params: GeneratorParams | None = None) -> MarketStream:
    """Generate a market stream.

    Deterministic in ``params.seed``. Contains no notion of decision or
    execution timing.
    """
    p = params if params is not None else GeneratorParams()
    rng = np.random.default_rng(p.seed)

    signal = _latent_path(p, rng)

    # The latent state tilts the price increment. Under the decoupled control
    # the tilt is removed but the state path is unchanged, so the two processes
    # are identical apart from the link being tested.
    tilt = 0.0 if p.decoupled else signal.astype(np.float64)
    shocks = rng.normal(0.0, p.noise_per_event, size=p.n_events)
    increments = p.drift_per_event * tilt + shocks

    mid = np.empty(p.n_events, dtype=np.float64)
    mid[0] = 100.0
    mid[1:] = mid[0] + np.cumsum(increments[:-1])

    # Order flow tilt, likewise removed under the decoupled control.
    flow_tilt = 0.0 if p.decoupled else signal.astype(np.float64)
    buy_fraction = np.clip(
        0.5 + p.flow_sensitivity * flow_tilt + rng.normal(0.0, 0.05, size=p.n_events),
        0.0,
        1.0,
    )

    # A wider spread and thinner depth while the state is active reflects
    # liquidity withdrawal, and is observable rather than hidden.
    activity = np.abs(signal.astype(np.float64))
    spread = p.base_spread * (1.0 + activity)
    depth = p.base_size * (1.0 - 0.5 * activity)
    imbalance = 2.0 * buy_fraction - 1.0
    bid_size = depth * (1.0 - imbalance)
    ask_size = depth * (1.0 + imbalance)

    times_ns = np.arange(p.n_events, dtype=np.int64) * p.event_spacing_ns

    return MarketStream(
        times_ns=times_ns,
        mid=mid,
        signal=signal,
        buy_fraction=buy_fraction,
        spread=spread,
        bid_size=bid_size,
        ask_size=ask_size,
    )


def with_persistence(
    params: GeneratorParams, mode: Literal["geometric", "persistent"]
) -> GeneratorParams:
    """Return a copy of ``params`` with the persistence mode switched."""
    return replace(params, persistence_mode=mode)


def decoupled_control(params: GeneratorParams) -> GeneratorParams:
    """Return a copy of ``params`` with the state-to-market link removed."""
    return replace(params, decoupled=True)
